// Compile the schema catalogue into static GROQ constants so TypeGen can
// evaluate every query. Re-run when the version-controlled models change.
import {writeFile} from 'node:fs/promises';
import {pageDocumentTypes,pageProjection,profileProjection,detailsProjection} from '../src/lib/page-query.ts';
const documentTypes=JSON.stringify(['siteSettings','homePage','programme','project','story','report','partner',...pageDocumentTypes]);
const values={pageProjection,profileProjection,detailsProjection,documentTypes};
await writeFile('src/lib/page-projections.ts','// Generated by scripts/generate-page-projections.mjs. Do not edit by hand.\n'+Object.entries(values).map(([name,value])=>`export const ${name} = ${JSON.stringify(value)};`).join('\n')+'\n');
console.log('Static CMS projections generated.');
